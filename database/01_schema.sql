-- Clean install: tables must not already exist.
CREATE TABLE department (
 department_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1001) PRIMARY KEY,
 department_name VARCHAR2(80) NOT NULL UNIQUE,
 location VARCHAR2(100) NOT NULL
);
CREATE TABLE employee (
 employee_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1001) PRIMARY KEY,
 employee_name VARCHAR2(100) NOT NULL,
 date_of_birth DATE NOT NULL,
 gender VARCHAR2(20), phone VARCHAR2(20),
 email VARCHAR2(120) NOT NULL UNIQUE, address VARCHAR2(250),
 join_date DATE NOT NULL, designation VARCHAR2(80) NOT NULL,
 department_id NUMBER NOT NULL,
 CONSTRAINT fk_emp_dept FOREIGN KEY (department_id) REFERENCES department(department_id)
);
CREATE TABLE attendance (
 attendance_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1001) PRIMARY KEY,
 employee_id NUMBER NOT NULL, attendance_date DATE NOT NULL,
 check_in_time VARCHAR2(5), check_out_time VARCHAR2(5),
 attendance_status VARCHAR2(12) NOT NULL,
 CONSTRAINT fk_att_emp FOREIGN KEY(employee_id) REFERENCES employee(employee_id),
 CONSTRAINT uq_att UNIQUE(employee_id,attendance_date),
 CONSTRAINT ck_att_status CHECK(attendance_status IN ('Present','Absent','Leave')),
 CONSTRAINT ck_att_time CHECK((check_in_time IS NULL OR REGEXP_LIKE(check_in_time,'^([01][0-9]|2[0-3]):[0-5][0-9]$')) AND (check_out_time IS NULL OR REGEXP_LIKE(check_out_time,'^([01][0-9]|2[0-3]):[0-5][0-9]$')))
);
CREATE TABLE employee_leave (
 leave_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1001) PRIMARY KEY,
 employee_id NUMBER NOT NULL, leave_type VARCHAR2(35) NOT NULL,
 from_date DATE NOT NULL, to_date DATE NOT NULL, reason VARCHAR2(250),
 leave_status VARCHAR2(12) DEFAULT 'Pending' NOT NULL,
 CONSTRAINT fk_leave_emp FOREIGN KEY(employee_id) REFERENCES employee(employee_id),
 CONSTRAINT ck_leave_dates CHECK(to_date >= from_date),
 CONSTRAINT ck_leave_status CHECK(leave_status IN ('Pending','Approved','Rejected'))
);
-- SQL table name EMPLOYEE_LEAVE avoids the Oracle keyword LEAVE while retaining the Phase 1 Leave entity.
CREATE TABLE salary (
 salary_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1001) PRIMARY KEY,
 employee_id NUMBER NOT NULL, basic_salary NUMBER(12,2) NOT NULL,
 allowance NUMBER(12,2) DEFAULT 0 NOT NULL, bonus NUMBER(12,2) DEFAULT 0 NOT NULL,
 deduction NUMBER(12,2) DEFAULT 0 NOT NULL, effective_from DATE NOT NULL,
 CONSTRAINT fk_salary_emp FOREIGN KEY(employee_id) REFERENCES employee(employee_id),
 CONSTRAINT uq_salary_version UNIQUE(employee_id,effective_from),
 CONSTRAINT ck_salary_positive CHECK(basic_salary >= 0 AND allowance >= 0 AND bonus >= 0 AND deduction >= 0)
);
CREATE TABLE payroll (
 payroll_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1001) PRIMARY KEY,
 employee_id NUMBER NOT NULL, salary_id NUMBER NOT NULL,
 payroll_month NUMBER(2) NOT NULL, payroll_year NUMBER(4) NOT NULL,
 gross_salary NUMBER(12,2) NOT NULL, total_deduction NUMBER(12,2) NOT NULL,
 net_salary NUMBER(12,2) NOT NULL, payment_date DATE,
 CONSTRAINT fk_pay_emp FOREIGN KEY(employee_id) REFERENCES employee(employee_id),
 CONSTRAINT fk_pay_salary FOREIGN KEY(salary_id) REFERENCES salary(salary_id),
 CONSTRAINT uq_pay_month UNIQUE(employee_id,payroll_year,payroll_month),
 CONSTRAINT ck_pay_month CHECK(payroll_month BETWEEN 1 AND 12),
 CONSTRAINT ck_pay_year CHECK(payroll_year BETWEEN 2000 AND 2100),
 CONSTRAINT ck_pay_values CHECK(gross_salary >= 0 AND total_deduction >= 0 AND net_salary >= 0 AND net_salary = gross_salary - total_deduction)
);
COMMIT;
